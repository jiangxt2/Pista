    val dir = new java.io.File(outputDir)
    if (dir.exists()) {
      def deleteRecursively(file: java.io.File): Unit = {
        if (file.isDirectory)
          file.listFiles().foreach(deleteRecursively)
        file.delete()
      }
      deleteRecursively(dir)
    }
  }

