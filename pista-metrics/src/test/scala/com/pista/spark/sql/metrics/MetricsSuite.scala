  // ==================== MetricsQueue testing ====================

  test("MetricsQueue should correctly enqueue and dequeue") {
    val queue = new MetricsQueue[String](10, DropPolicy.DropOldest)

    assert(queue.offer("a"))
    assert(queue.offer("b"))
    assert(queue.offer("c"))
    assert(queue.size == 3)

    val drained = queue.drain(2)
    assert(drained == Seq("a", "b"))
    assert(queue.size == 1)
  }

  test("MetricsQueue is full should discard the oldest entries by the DropOldest strategy") {
    val queue = new MetricsQueue[Int](3, DropPolicy.DropOldest)

    queue.offer(1)
    queue.offer(2)
    queue.offer(3)
    assert(queue.size == 3)

    // Queue full, should overwrite the oldest (1)
    queue.offer(4)
    assert(queue.size == 3)
    assert(queue.droppedCount == 1)

    val drained = queue.drain(10)
    assert(drained == Seq(2, 3, 4))
  }

  test("MetricsQueue is full should discard the newest entries by the DropNewest strategy") {
    val queue = new MetricsQueue[Int](3, DropPolicy.DropNewest)

    queue.offer(1)
    queue.offer(2)
    queue.offer(3)

    // Queue full, should overwrite the current (4)
    val result = queue.offer(4)
    assert(!result)
    assert(queue.droppedCount == 1)

    val drained = queue.drain(10)
    assert(drained == Seq(1, 2, 3))
  }

  // ==================== TaskAggregator Test ====================

  test("TaskAggregator should correctly aggregate task metrics Task metrics have been aggregated correctly by the Task Aggregator.") {
    val aggregator = new TaskAggregator()

    // record the execution duration of 10 tasks 10 tasks Task the execution time
    val durations = Seq(100L, 200L, 300L, 400L, 500L, 600L, 700L, 800L, 900L, 1000L)
    durations.foreach(d => aggregator.record(1, 0, d))

    val result = aggregator.aggregateAndClear(1, 0, "app-123")
    assert(result.isDefined)

    val metrics = result.get
    assert(metrics.appId == "app-123")
    assert(metrics.stageId == 1)
    assert(metrics.stageAttemptId == 0)
    assert(metrics.taskCount == 10)
    assert(metrics.durationMin == 100L)
    assert(metrics.durationMax == 1000L)
    assert(metrics.durationAvg == 550L)
    // percentile calculation: index = (size - 1) * p
    // P50: index = 9 * 0.50 = 4, sorted(4) = 500
    assert(metrics.durationP50 == 500L)
    // P95: index = 9 * 0.95 = 8, sorted(8) = 900
    assert(metrics.durationP95 == 900L)
    // P99: index = 9 * 0.99 = 8, sorted(8) = 900
    assert(metrics.durationP99 == 900L)
    assert(metrics.skewRatio == 2.0) // 1000 / 500
  }

  test("TaskAggregator Aggregates and should clear data") {
    val aggregator = new TaskAggregator()

    aggregator.record(1, 0, 100L)
    aggregator.record(1, 0, 200L)

    val first = aggregator.aggregateAndClear(1, 0, "app-123")
    assert(first.isDefined)
    assert(first.get.taskCount == 2)

    // re-aggregation should return null None
    val second = aggregator.aggregateAndClear(1, 0, "app-123")
    assert(second.isEmpty)
  }

  test("TaskAggregator should support concurrent records across multiple stages Stage concurrent records") {
    val aggregator = new TaskAggregator()

    // Stage 1
    aggregator.record(1, 0, 100L)
    aggregator.record(1, 0, 200L)

    // Stage 2
    aggregator.record(2, 0, 300L)
    aggregator.record(2, 0, 400L)

    assert(aggregator.trackedStageCount == 2)

    val stage1 = aggregator.aggregateAndClear(1, 0, "app-123")
    assert(stage1.isDefined)
    assert(stage1.get.taskCount == 2)
    assert(stage1.get.durationAvg == 150L)

    val stage2 = aggregator.aggregateAndClear(2, 0, "app-123")
    assert(stage2.isDefined)
    assert(stage2.get.taskCount == 2)
    assert(stage2.get.durationAvg == 350L)
  }

