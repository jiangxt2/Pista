  // ==================== TaskAggregator Skew Detection Test ====================

  test("TaskAggregator should correctly detect data skew (skewed)") {
    val aggregator = new TaskAggregator()

    // simulation 10 task Taskwhere 1 one is significantly slower (skewed)
    val durations = Seq(100L, 100L, 100L, 100L, 100L, 100L, 100L, 100L, 100L, 1000L)
    durations.foreach(d => aggregator.record(1, 0, d))

    val result = aggregator.aggregateAndClear(1, 0, "app-123")
    assert(result.isDefined)

    val metrics = result.get
    assert(metrics.skewRatio == 10.0) // 1000 / 100
    assert(metrics.skewRatio > 2.0, "Should detect data skew")
  }

  test("TaskAggregator should correctly detect data skew (no skew)") {
    val aggregator = new TaskAggregator()

    // simulation 10 tasks Taskuniform execution time across tasks
    val durations = Seq(100L, 110L, 105L, 95L, 100L, 105L, 100L, 95L, 100L, 100L)
    durations.foreach(d => aggregator.record(1, 0, d))

    val result = aggregator.aggregateAndClear(1, 0, "app-123")
    assert(result.isDefined)

    val metrics = result.get
    assert(metrics.skewRatio < 2.0, "should not detect skew")
  }

  // ==================== Integration Testing ====================

  test("should be able to extract QueryPlan information from a simple query") {
    val sparkSession = spark
    import sparkSession.implicits._

    // Create test data.
    val df = Seq((1, "Alice"), (2, "Bob"), (3, "Charlie")).toDF("id", "name")
    df.createOrReplaceTempView("test_table")

    // Execute query
    val result = spark.sql("SELECT * FROM test_table WHERE id > 1")
    result.collect()

    // Obtain QueryExecution.
    val qe = result.queryExecution

    // Validate that the plan exists
    assert(qe.logical != null)
    assert(qe.optimizedPlan != null)
    assert(qe.sparkPlan != null)
    assert(qe.executedPlan != null)

    // Validate that the plan string is not null
    assert(qe.logical.toString.nonEmpty)
    assert(qe.optimizedPlan.toString.nonEmpty)
    assert(qe.sparkPlan.toString.nonEmpty)
    assert(qe.executedPlan.toString.nonEmpty)
  }

  test("should be able to extract plan information from a Join query") {
    val sparkSession = spark
    import sparkSession.implicits._

    // Create test data.
    val df1 = Seq((1, "Alice"), (2, "Bob")).toDF("id", "name")
    val df2 = Seq((1, 100), (2, 200)).toDF("id", "score")

    df1.createOrReplaceTempView("users")
    df2.createOrReplaceTempView("scores")

    // execution Join query
    val result = spark.sql("SELECT u.name, s.score FROM users u JOIN scores s ON u.id = s.id")
    result.collect()

    // Obtain QueryExecution.
    val qe = result.queryExecution

    // Validate the plan contains a Join node.
    val planStr = qe.sparkPlan.toString
    assert(planStr.contains("Join") || planStr.contains("BroadcastHashJoin") || planStr.contains("SortMergeJoin"))
  }

  test("It should be able to extract plan information from an aggregate query") {
    val sparkSession = spark
    import sparkSession.implicits._

    // Create test data.
    val df = Seq((1, "A", 100), (2, "A", 200), (3, "B", 150)).toDF("id", "category", "value")
    df.createOrReplaceTempView("data")

    // Execute aggregation query
    val result = spark.sql("SELECT category, SUM(value) as total FROM data GROUP BY category")
    result.collect()

    // Obtain QueryExecution.
    val qe = result.queryExecution

    // Validate that the plan includes aggregation nodes
    val planStr = qe.sparkPlan.toString
    assert(planStr.contains("Aggregate") || planStr.contains("HashAggregate"))
  }
